@Composable
fun LocalProBottomBar(
    selectedRoute: String,
    onRouteSelected: (String) -> Unit,
    modifier: Modifier = Modifier,
    isProvider: Boolean = false
) {
    val navItems = if (isProvider) {
        listOf(
            BottomNavItem("provider_home", "Dashboard", Icons.Default.Dashboard),
            BottomNavItem("bookings", "Jobs", Icons.Default.Work),
            BottomNavItem("profile", "Profile", Icons.Default.Person)
        )
    } else {
        listOf(
            BottomNavItem("home", "Home", Icons.Default.Home),
            BottomNavItem("explore", "Explore", Icons.Default.Explore),
            BottomNavItem("bookings", "Bookings", Icons.Default.Schedule),
            BottomNavItem("profile", "Profile", Icons.Default.Person)
        )
    }

    NavigationBar(
        modifier = modifier,
        containerColor = MaterialTheme.colorScheme.surface,
        tonalElevation = 8.dp
    ) {
        navItems.forEach { item ->
            val isSelected = selectedRoute == item.route
            NavigationBarItem(
                selected = isSelected,
                onClick = { onRouteSelected(item.route) },
                icon = {
                    Icon(
                        imageVector = item.icon,
                        contentDescription = item.label,
                        tint = if (isSelected) MaterialTheme.colorScheme.primary else MaterialTheme.colorScheme.onSurfaceVariant
                    )
                },
                label = {
                    Text(
                        text = item.label,
                        style = MaterialTheme.typography.labelSmall,
                        fontWeight = if (isSelected) FontWeight.Bold else FontWeight.Normal,
                        color = if (isSelected) MaterialTheme.colorScheme.primary else MaterialTheme.colorScheme.onSurfaceVariant
                    )
                },
                colors = NavigationBarItemDefaults.colors(
                    indicatorColor = MaterialTheme.colorScheme.primaryContainer
                )
            )
        }
    }
}
